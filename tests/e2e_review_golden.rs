//! SL-268 PHASE-01 — the behaviour-preservation golden for `doctrine review`.
//!
//! D4 (design.md sec-8) splits `src/review.rs` into an engine tier
//! (`review_ledger`) and a command tier (`review`) starting PHASE-02, and later
//! phases (IMP-029) change fail-safe reads, the turn journal, and more. This
//! file pins TODAY's CLI surface — stdout, stderr, exit code, and the authored
//! ledger TOML — byte-exact over the BUILT binary, so every later phase can
//! hold it green unchanged as the proof nothing behavioural moved along with
//! the code (RV-396 `F-7`).
//!
//! The only normalisation is the fixture root's string form → `<ROOT>`: it
//! covers `new`'s created directory and every path-bearing error. Nothing else
//! is carved out — a review ledger carries no dates/uids, `--color never` is
//! passed explicitly on every invocation so a stray `CLICOLOR_FORCE` cannot
//! inject ANSI, and the reservation degrade line is deterministic (no remote
//! configured from a bare tempdir).
//!
//! Expected strings are generated by running the built binary against each
//! fixture once and pasting the result — no bless/update env var exists in
//! this repo's `tests/e2e_*golden*.rs` family (A4), and inventing one here
//! would be new. A behaviour that looks like a bug is still pinned as-is; any
//! such oddity is called out in the phase notes, not carved out of the golden.

