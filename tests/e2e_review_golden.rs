/// `doctrine review <args...> -p <root> --color never` over the built binary —
/// the single invocation shape used by every test here, so a stray
/// `CLICOLOR_FORCE` cannot inject ANSI into a byte-exact assertion.
fn run(root: &Path, args: &[&str]) -> Output {
    common::doctrine_cmd(root)
        .arg("review")
        .args(args)
        .arg("-p")
        .arg(root)
        .arg("--color")
        .arg("never")
        .output()
        .expect("spawn doctrine")
}

/// The `run()` shape, but with `input` piped to the child's stdin (SL-268
/// PHASE-07 T1) — `run()`'s `Command::output()` leaves stdin null, so a `-`
/// case needs this sibling: spawn, write, then wait.
fn run_stdin(root: &Path, args: &[&str], input: &str) -> Output {
    use std::io::Write as _;
    use std::process::Stdio;

    let mut child = common::doctrine_cmd(root)
        .arg("review")
        .args(args)
        .arg("-p")
        .arg(root)
        .arg("--color")
        .arg("never")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn doctrine");
    child
        .stdin
        .take()
        .expect("piped stdin")
        .write_all(input.as_bytes())
        .expect("write stdin");
    child.wait_with_output().expect("wait for doctrine")
}

fn stdout(out: &Output) -> String {
    String::from_utf8(out.stdout.clone()).expect("utf8 stdout")
}
fn stderr(out: &Output) -> String {
    String::from_utf8(out.stderr.clone()).expect("utf8 stderr")
}

fn tmp() -> tempfile::TempDir {
    tempfile::tempdir().expect("tempdir")
}

/// The write-path skip (ISS-260, mirrored from `e2e_adr_cli_golden.rs`): a
/// guard-`Write` review verb (new/raise/dispose/verify/contest/withdraw/
/// conclude/unlock — `src/commands/guard.rs:112-125`) is CORRECTLY
/// guard-refused inside a marked worker fork, so its golden's write/no-write
/// assertions no longer hold there — not a regression, just the wrong place to
/// run it. `list`/`show`/`status`/`prime`/`paths` are guard-`Read` and never
/// skip (A2). The coord-tree unmarked run is authoritative (VA-1).
fn skip_under_worker_marker(test_name: &str) -> bool {
    if common::under_worker_marker() {
        eprintln!("{test_name}: worker fork — skipping (authored write, guard-refused by design)");
        true
    } else {
        false
    }
}

/// Replace the fixture root's string form with `<ROOT>` — the ONLY
/// normalisation (EX-3). Tries `canonicalize()`'s display form first, then
/// `root.display()`, in case a symlinked tmp makes the two differ (both are
/// "the fixture root"). Applied to stdout/stderr only — ledger bytes carry no
/// root path and are compared raw.
fn norm(root: &Path, s: &str) -> String {
    let mut out = s.to_owned();
    if let Ok(canon) = root.canonicalize() {
        out = out.replace(&canon.display().to_string(), "<ROOT>");
    }
    out.replace(&root.display().to_string(), "<ROOT>")
}

/// Hand-seed one review's authored ledger + brief.
fn seed_review(root: &Path, id: u32, toml: &str, md: &str) {
    let dir = root.join(format!(".doctrine/review/{id:03}"));
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join(format!("review-{id:03}.toml")), toml).unwrap();
    fs::write(dir.join(format!("review-{id:03}.md")), md).unwrap();
}

/// Hand-seed a minimal slice target — mirrors `src/review.rs`'s in-file
/// `plant_slice_with_selectors` fixture (design D9's path-set shape). Every
/// selector rides `intent = "design-target"` (`prime` unions all intents).
/// Enough for `ensure_ref_resolves` (a dir probe) and `slice::selector_paths`
/// (which reads the toml + md).
fn seed_slice(root: &Path, id: u32, selectors: &[&str]) {
    let dir = root.join(format!(".doctrine/slice/{id:03}"));
    fs::create_dir_all(&dir).unwrap();
    let mut toml = format!(
        "id = {id}\nslug = \"t\"\ntitle = \"T\"\nstatus = \"proposed\"\ncreated = \"2026-01-01\"\nupdated = \"2026-01-01\"\n"
    );
    for sel in selectors {
        toml.push_str(&format!(
            "\n[[selector]]\nselector = \"{sel}\"\nintent = \"design-target\"\n"
        ));
    }
    fs::write(dir.join(format!("slice-{id:03}.toml")), toml).unwrap();
    fs::write(dir.join(format!("slice-{id:03}.md")), "## Scope\n").unwrap();
}

/// Hand-seed a minimal ADR target (for the "target is not a slice" prime
/// refusal fixture) — just enough for `ensure_ref_resolves`.
fn seed_adr(root: &Path, id: u32) {
    let dir = root.join(format!(".doctrine/adr/{id:03}"));
    fs::create_dir_all(&dir).unwrap();
    let toml = format!(
        "id = {id}\nslug = \"a\"\ntitle = \"A\"\nstatus = \"accepted\"\ncreated = \"2026-01-01\"\nupdated = \"2026-01-01\"\ntags = []\n[relationships]\nsupersedes = []\nsuperseded_by = []\nrelated = []\n"
    );
    fs::write(dir.join(format!("adr-{id:03}.toml")), toml).unwrap();
    fs::write(dir.join(format!("adr-{id:03}.md")), "# ADR\n").unwrap();
}

/// Hand-seed a stale lock (S14/T10) — the `pid`/`acquired` diagnostic body
/// `LockGuard::acquire` writes (`src/review.rs:2371-2373`).
fn seed_lock(root: &Path, id: u32, body: &str) {
    let dir = root.join(format!(".doctrine/state/review/{id:03}"));
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("lock"), body).unwrap();
}

/// Read back one review's authored ledger bytes.
fn ledger(root: &Path, id: u32) -> String {
    fs::read_to_string(root.join(format!(".doctrine/review/{id:03}/review-{id:03}.toml"))).unwrap()
}

/// A minimal single-finding ledger at review id 1, target `SL-001`, default
/// raiser/responder labels — the shared base for the role/state refusal
/// fixtures (only the finding's `status` varies).
fn seed_one_finding(root: &Path, status: &str) {
    let toml = format!(
        "id    = 1\nslug  = \"t\"\ntitle = \"T\"\n\n[review]\nfacet     = \"design\"\nraiser    = \"raiser\"\nresponder = \"responder\"\n\n[target]\nref   = \"SL-001\"\n\n[[finding]]\nid = \"F-1\"\nstatus = \"{status}\"\nseverity = \"blocker\"\ntitle = \"T1\"\ndetail = \"D1\"\n"
    );
    seed_review(root, 1, &toml, "# brief\n");
}

